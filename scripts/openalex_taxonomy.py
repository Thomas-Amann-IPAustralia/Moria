"""Write config/openalex_taxonomy.yaml: each OpenAlex topic's subfield, and each field's domain (D-032).

`moria measure series` tests an OpenAlex topic's count as a share of its subfield, a subfield's of its field, a field's
of its domain and a domain's of all works, so a shift in what OpenAlex indexes in a whole field (D-031: Physics and
Astronomy's share of all works doubled in a year) shows once, at the level where it happens, not in every topic under
it. A subfield's field is its id's first two digits; the topics and fields are listed here.

OpenAlex's metadata is CC0. About 25 list calls of the free daily budget; the key is read from OPENALEX_API_KEY and
refused if it has a prepaid balance (as the collector does). Run it again when OpenAlex revises its topics:

    uv run python scripts/openalex_taxonomy.py
"""

from __future__ import annotations

import os
import sys
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from moria.config import load_config  # noqa: E402
from moria.http import PoliteClient  # noqa: E402

BASE = "https://api.openalex.org"
OUT = ROOT / "config" / "openalex_taxonomy.yaml"


def tail(url: str) -> str:
    return url.rstrip("/").rsplit("/", 1)[-1]


def main() -> int:
    key = os.environ.get("OPENALEX_API_KEY", "")
    if not key:
        print("OPENALEX_API_KEY is not set (docs/setup.md)", file=sys.stderr)
        return 2
    headers = {"Authorization": f"Bearer {key}"}
    client = PoliteClient(load_config().http)
    try:
        limits = client.get(f"{BASE}/rate-limit", headers=headers).json().get("rate_limit", {})
        if limits.get("prepaid_remaining_usd"):
            print("the key has a prepaid balance: refused", file=sys.stderr)
            return 2
        topics: dict[str, str] = {}
        cursor = "*"
        while cursor:
            data = client.get(f"{BASE}/topics", params={"per_page": "200", "cursor": cursor,
                                                         "select": "id,subfield"}, headers=headers).json()  # fmt: skip
            for t in data["results"]:
                topics[tail(t["id"])] = tail(t["subfield"]["id"])
            cursor = data["meta"].get("next_cursor")
        fields = {}
        data = client.get(f"{BASE}/fields", params={"per_page": "200", "select": "id,domain"}, headers=headers).json()
        for f in data["results"]:
            fields[tail(f["id"])] = tail(f["domain"]["id"])
    finally:
        client.close()
    lines = [
        "# OpenAlex's taxonomy for `moria measure series` (D-032): each topic's subfield and each field's domain. A",
        "# subfield's field is the first two digits of its id. Generated by scripts/openalex_taxonomy.py from",
        f"# {BASE}/topics and /fields on {datetime.now(UTC).date().isoformat()} (CC0). Do not edit by hand.",
        "version: 1",
        "fields:",
        *[f'  "{k}": "{v}"' for k, v in sorted(fields.items(), key=lambda kv: int(kv[0]))],
        "topics:",
        *[f'  {k}: "{v}"' for k, v in sorted(topics.items(), key=lambda kv: int(kv[0].lstrip("T")))],
    ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(topics)} topics, {len(fields)} fields -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
