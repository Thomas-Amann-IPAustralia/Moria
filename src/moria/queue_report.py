"""`moria queue-report --as-of D`: the review queue, profiled for the public repo (aggregates only; day 5).

Counts by ring, type, view, quota pass and source, in the shortlist and the queue; the quotas against their fill;
the artefact flags carried; the ranking's sensitivity to each weight (design §8.2); the dossiers' checks; the
decision model's suggestions as distributions (whether they are used in the ranking, and what `moria eval pathways`
found); and the register's events and statuses. No labels, titles, keyphrases, URLs or candidate ids.
"""

from __future__ import annotations

import json
from collections import Counter
from datetime import date

from .config import ReviewConfig
from .detect import _matching
from .dossier import COMMAND as DOSSIER
from .pathways import COMMAND as PATHWAYS
from .pathways import EVAL
from .queue import COMMAND as QUEUE
from .rank import COMMAND as RANK
from .rank import files_of, largest_remainder, manifest_of
from .register import events, state
from .store import Store
from .tables import latest_manifest, read_rows


def _table(counter: Counter, head: str) -> list[str]:
    lines = [f"| {head} | Count |", "|---|---:|"]
    for k, v in sorted(counter.items(), key=lambda kv: (-kv[1], str(kv[0]))):
        lines.append(f"| {k} | {v} |")
    return lines


def queue_report(store: Store, cfg: ReviewConfig, as_of: date) -> str:
    rm, qm = _matching(store, RANK, as_of), _matching(store, QUEUE, as_of)
    pm = manifest_of(store, PATHWAYS, qm["params"]["pathways_run"])
    dm = manifest_of(store, DOSSIER, qm["params"]["dossier_run"])
    ranked = read_rows(files_of(store, rm, "review/")["ranked.parquet"])
    qf = files_of(store, qm, "review/")
    queue, sens = read_rows(qf["queue.parquet"]), read_rows(qf["sensitivity.parquet"])
    sug = read_rows(files_of(store, pm, "interpretation/pathways/")["pathways.parquet"])
    short = [r for r in ranked if r["shortlisted"]]
    size = cfg.queue.size
    caps = largest_remainder(size, cfg.queue.rings)
    rings = Counter(q["ring"] for q in queue)
    lines = [
        f"# The review queue: the scan of {as_of.isoformat()}", "",
        f"Runs: rank `{rm['run_id']}`, dossiers `{dm['run_id']}`, pathways `{pm['run_id']}`, queue `{qm['run_id']}`. "
        "Generated by `moria queue-report`; aggregates only (no labels, titles, keyphrases, links or ids).", "",
        "## Headline", "",
        f"- {len(ranked)} candidates scored; a shortlist of {len(short)} with dossiers and the decision model's "
        f"suggestions; a queue of {len(queue)} for review.",
        f"- Ring quotas: core {rings['core']} of {caps['core']}, adjacent {rings['adjacent']} of {caps['adjacent']}, "
        f"wider world {rings['wider_world']} of {caps['wider_world']}; "
        f"{sum(1 for q in queue if q['pass'] > 1)} places filled outside a quota.",
        f"- {sum(1 for q in queue if q['flags'])} queued candidates carry an artefact flag (shown, never hidden).",
        "- The decision model's suggestions are " + ("used in the ranking." if cfg.pathways.use_in_ranking else
                                                     "recorded and shown, not used in the ranking (D-029)."), "",
    ]  # fmt: skip
    for title, rows in (("The queue", queue), ("The shortlist", short)):
        lines += [f"## {title}", ""]
        lines += [*_table(Counter(r["type"] for r in rows), "Type"), ""]
        lines += [*_table(Counter(r["ring"] for r in rows), "Ring"), ""]
        lines += [*_table(Counter(r["source"] for r in rows), "Source"), ""]
    lines += [*_table(Counter(q["view"] for q in queue), "Picked by view"), ""]
    lines += [*_table(Counter(r["ring_basis"] for r in ranked), "Ring basis (every candidate)"), ""]
    lines += ["## Sensitivity of the queue to the weights", "",
              f"Each weight times each factor, the queue chosen again: places of the {size} still in it."
              + ("" if cfg.pathways.use_in_ranking else " Pathway and impact have no effect while the suggestions "
                 "are not used in the ranking."), "",
              "| View | Component | Factor | Places kept |", "|---|---|---:|---:|"]  # fmt: skip
    for s in sens:
        lines.append(f"| {s['view']} | {s['component']} | {s['factor']:g} | {s['overlap']} of {s['size']} |")
    checks = Counter()
    for k, v in (dm.get("counts") or {}).items():
        if k.startswith("check_"):
            checks[k.removeprefix("check_")] = v
    lines += ["", "## The dossiers' checks (dossiers flagged, of the shortlist)", "", *_table(checks, "Check")]
    lines += ["", f"OpenAlex sample works: {dm['counts'].get('openalex_samples_ok', 0)} fetched, "
              f"{dm['counts'].get('openalex_concentrated', 0)} concentrated in one venue; "
              f"{dm['counts'].get('openalex_calls', 0)} calls of the free daily budget.", ""]  # fmt: skip
    lines += [
        "## The decision model's suggestions (distributions over the shortlist)",
        "",
        f"Author: {pm['params'].get('author') or 'none'}; questions {pm['params'].get('questions')}.",
        "",
    ]
    if any(r["pathway_top"] for r in sug):
        lines += [*_table(Counter(r["pathway_top"] for r in sug), "Top pathway"), ""]
        for name in ("order_top", "horizon_top", "stance_top", "impact_top", "origin_top"):
            lines += [*_table(Counter(r[name] for r in sug), name.removesuffix("_top").capitalize()), ""]
        ps = [json.loads(r["pathways"]) for r in sug if r["pathways"]]
        lines += ["| Pathway | Lowest | Median | Highest |", "|---|---:|---:|---:|"]
        for pid in ("P1", "P2", "P3", "P4", "P5", "P6"):
            vals = sorted(p[pid] for p in ps)
            lines.append(f"| {pid} | {vals[0]:.3f} | {vals[len(vals) // 2]:.3f} | {vals[-1]:.3f} |")
        lines.append("")
    ev = latest_manifest(store, EVAL)
    if ev and ev["status"] == "passed" and ev["params"].get("as_of") == as_of.isoformat():
        r = ev["params"]["result"]
        lines += [f"`moria eval pathways` (`{ev['run_id']}`): separation {r['separation']:.3f} (rule >= "
                  f"{r['rule']['min_separation']}), spread {r['spread']:.3f} (rule >= {r['rule']['min_spread']}): "
                  f"{'passes' if r['passes'] else 'fails'}. See `reports/eval/pathways.md`.", ""]  # fmt: skip
    st = state(events(store))
    evs = Counter(e["kind"] for e in events(store))
    lines += ["## The register", "", *_table(evs, "Events by kind"), ""]
    lines += _table(Counter(s["status"] for s in st.values() if not s["signal_id"].startswith("miss-")), "Status")
    lines += ["", "## How to read these numbers", "",
              "- Scores are weighted geometric means of percentiles, so they rank within a scan; they are not "
              "probabilities and do not compare across scans.",
              "- A place 'filled outside a quota' is a ring's unused place given to another ring (pass 2), or a "
              "source's cap relaxed (pass 3).",
              "- 'Places kept' near the queue's size means the queue barely depends on that weight; a low number "
              "means the weight decides much of it, and is worth the owner's view after the first review "
              "round."]  # fmt: skip
    return "\n".join(lines) + "\n"
