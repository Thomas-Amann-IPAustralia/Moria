"""`moria scan-report --as-of D`: a profile of one scan for the public repo (`reports/scan.md`): candidates by type,
detector, source, family and ring, the artefact flags, the series tested, the document volumes behind the weak
signals, the ingestion incidents and the seeded-artefact evaluation. Counts only: no labels, keyphrases, titles or
URLs (CLAUDE.md: repo reports hold aggregates only)."""

from __future__ import annotations

from collections import Counter, defaultdict
from datetime import date

from .artefacts import CHECKS
from .artefacts import COMMAND as ART
from .concepts import COMMAND as DOCS
from .config import DetectConfig
from .detect import COMMAND as DET
from .detect import TYPES
from .measures import COMMAND as SER
from .monitor import COMMAND as MON
from .seeded import COMMAND as EVAL
from .store import Store
from .tables import cache_root, fetch_outputs, latest_manifest, read_rows


def _files(store: Store, m: dict, prefix: str) -> dict:
    return {k.rsplit("/", 1)[1]: p for k, p in fetch_outputs(store, m, prefix, cache_root()).items()}


def _n(v) -> str:
    return f"{v:,}" if isinstance(v, int) else str(v)


def scan_report(store: Store, cfg: DetectConfig, as_of: date) -> str:
    runs = {c: latest_manifest(store, c) for c in (MON, SER, DOCS, DET, ART)}
    for c, m in runs.items():
        if not m or m["status"] != "passed" or m["params"].get("as_of") != as_of.isoformat():
            raise ValueError(f"no passed {c} run for {as_of}; run `moria scan --as-of {as_of}` first")
    out = [f"# Scan of {as_of}", "", f"Generated by `moria scan-report --as-of {as_of}` from the scan's runs; "
           "aggregates only. Candidates are what the detectors raised; the artefact checks mark, never hide, them "
           "(design §8.2, §8.3). Ranking, quotas and dossiers come next (day 5).", "",
           "| Stage | Run | Commit | Dirty |", "|---|---|---|---|"]  # fmt: skip
    for c, m in runs.items():
        out.append(f"| `{c}` | `{m['run_id']}` | `{(m['git'].get('commit') or '')[:7]}` | {m['git'].get('dirty')} |")
    cands = read_rows(_files(store, runs[DET], "candidates/")["candidates.parquet"])
    arts = {r["candidate_id"]: r for r in read_rows(_files(store, runs[ART], "candidates/")["artefacts.parquet"])}
    clean = sum(1 for c in cands if arts[c["candidate_id"]]["clean"])
    by_type = Counter(c["type"] for c in cands)
    out += ["", f"**{len(cands):,} candidates, {clean:,} with no artefact flag.** "
            + "; ".join(f"{t.replace('_', ' ')}: {by_type.get(t, 0):,}" for t in TYPES) + ".", ""]  # fmt: skip

    # by type and check
    out += ["## Candidates by type and artefact check", "",
            "| Type | Candidates | Clean | " + " | ".join(c.replace("_", " ") for c in CHECKS) + " |",
            "|---|" + "---:|" * (2 + len(CHECKS))]  # fmt: skip
    for t in TYPES:
        cs = [c for c in cands if c["type"] == t]
        flags = Counter(f for c in cs for f in arts[c["candidate_id"]]["flags"])
        n_clean = sum(1 for c in cs if arts[c["candidate_id"]]["clean"])
        out.append(f"| {t.replace('_', ' ')} | {len(cs):,} | {n_clean:,} | "
                   + " | ".join(f"{flags.get(k, 0):,}" for k in CHECKS) + " |")  # fmt: skip

    # detectors
    out += ["", "## Detectors", "", "A candidate counts under every detector that fired on it.", "",
            "| Detector | Candidates | Clean |", "|---|---:|---:|"]  # fmt: skip
    det = Counter(d for c in cands for d in c["detectors"])
    det_clean = Counter(d for c in cands if arts[c["candidate_id"]]["clean"] for d in c["detectors"])
    for d, n in sorted(det.items(), key=lambda kv: (-kv[1], kv[0])):
        out.append(f"| {d.replace('_', ' ')} | {n:,} | {det_clean.get(d, 0):,} |")

    # by source (series) and by evidence family (documents)
    out += ["", "## Where they come from", "", "Series and AU/world pairs by source; weak signals from documents by "
            "the families of their evidence.", "", "| From | Trend | Acceleration | Weak signal | Anomaly | Clean |",
            "|---|---:|---:|---:|---:|---:|"]  # fmt: skip
    where: dict[str, Counter] = defaultdict(Counter)
    for c in cands:
        key = (f"{c['sources'][0]}" if c["subject_kind"] in ("series", "pair")
               else "documents: " + " + ".join(c["families"]) if c["families"] else f"{c['sources'][0]}")  # fmt: skip
        where[key][c["type"]] += 1
        where[key]["clean"] += arts[c["candidate_id"]]["clean"]
    for k in sorted(where):
        w = where[k]
        out.append(f"| {k} | " + " | ".join(f"{w.get(t, 0):,}" for t in (*TYPES, "clean")) + " |")
    rings: dict[str, Counter] = defaultdict(Counter)
    for c in cands:
        rings[" + ".join(c["rings"]) or "(none)"][c["type"]] += 1
    out += ["", "By the rings of their evidence (a series carries its card's rings; a GDELT group its own ring):", "",
            "| Rings | Trend | Acceleration | Weak signal | Anomaly |", "|---|---:|---:|---:|---:|"]  # fmt: skip
    for k in sorted(rings):
        out.append(f"| {k} | " + " | ".join(f"{rings[k].get(t, 0):,}" for t in TYPES) + " |")

    # series measures
    sf = _files(store, runs[SER], "measures/series/")
    rows = read_rows(sf["measures.parquet"], ["source", "frequency", "trend_dir", "trend_w1_q_bh", "trend_w2_q_bh",
                                              "trend_w3_q_bh", "accel", "anomaly", "cp_level_recent", "cp_steeper",
                                              "surge", "trend_windows"])  # fmt: skip
    sm = runs[SER]["counts"]
    out += ["", "## Series tested", "", f"{sm.get('series', 0):,} series; trends under Holm (the rule): "
            f"{sm.get('trends', 0):,}; under Benjamini-Hochberg, for comparison: {sm.get('trends_bh', 0):,}. "
            f"AU/world pairs: {sm.get('divergence_pairs', 0):,}, diverging: {sm.get('divergences', 0):,}.", "",
            "| Source | Frequency | Series | Testable windows | Trends | Accelerations | Anomalies | Level changes | "
            "Surges |", "|---|---|---:|---:|---:|---:|---:|---:|---:|"]  # fmt: skip
    agg: dict[tuple, Counter] = defaultdict(Counter)
    for r in rows:
        a = agg[(r["source"], r["frequency"])]
        a["series"] += 1
        a["windows"] += (r["trend_windows"] or 0) >= 2
        a["trends"] += bool(r["trend_dir"])
        a["accel"] += bool(r["accel"])
        a["anomaly"] += bool(r["anomaly"])
        a["level"] += bool(r["cp_level_recent"])
        a["surge"] += bool(r["surge"])
    for (s, f), a in sorted(agg.items()):
        out.append(f"| {s} | {f} | {a['series']:,} | {a['windows']:,} | {a['trends']:,} | {a['accel']:,} | "
                   f"{a['anomaly']:,} | {a['level']:,} | {a['surge']:,} |")  # fmt: skip
    out += ["", "Testable windows: series with at least two of the three trend windows covered and enough volume. "
            "Accelerations here are the bootstrap test alone; a candidate is also an acceleration when a change "
            "point to a steeper slope falls on a significant trend."]  # fmt: skip

    # documents
    df = _files(store, runs[DOCS], "measures/documents/")
    dm = runs[DOCS]["counts"]
    dc = cfg.documents
    out += ["", "## Documents behind the weak signals", "",
            f"Window: the {dc.window_days} days to {as_of}; baseline: the {dc.baseline_days} days before it. "
            f"{dm.get('items_window', 0):,} items in the window and {dm.get('items_baseline', 0):,} in the baseline "
            f"(dated items only; {dm.get('backlog_items', 0):,} undated items from a source's first collection are "
            "left out). Indicators: "
            f"new terms {dm.get('new_term', 0):,}, cross-family {dm.get('cross_family', 0):,}, cross-ring "
            f"{dm.get('cross_ring', 0):,}, low-base surges {dm.get('low_base_surge', 0):,}, new combinations "
            f"{dm.get('combinations_new', 0):,} and rising {dm.get('combinations_rising', 0):,}, micro-clusters of "
            f"novel items {dm.get('novel_micro_clusters', 0):,} (before the weak-signal minimum).", "",
            "| Source | Family | Onboarded | History from | Window groups | Baseline groups | Change per day |",
            "|---|---|---|---:|---:|---:|---:|"]  # fmt: skip
    for v in read_rows(df["volumes.parquet"]):
        ch = "no baseline" if v["change"] is None else f"{v['change']:+.0%}"
        start = v["coverage_start"].year if v["coverage_start"] else "-"
        out.append(f"| {v['source']} | {v['family']} | {v['onboarded_at']:%Y-%m-%d} | {start} | "
                   f"{v['window_groups']:,} | {v['baseline_groups']:,} | {ch} |")  # fmt: skip
    out += ["", "A source onboarded inside the baseline, or whose volume moved more than ±25%, is why most weak "
            "signals carry the source-break and coverage flags until daily collection has built a "
            "baseline."]  # fmt: skip

    # ingestion
    inc = read_rows(_files(store, runs[MON], "monitors/summary/")["incidents.parquet"])
    kinds = Counter(i["kind"] for i in inc)
    listed = ", ".join(f"{k.replace('_', ' ')} {n:,}" for k, n in sorted(kinds.items())) or "none"
    out += ["", "## Ingestion incidents", "", f"{len(inc):,} incidents to {as_of}: {listed}."]
    if inc:
        per = Counter((i["source"], i["kind"]) for i in inc)
        out += ["", "| Source | Incident | Days |", "|---|---|---:|"]
        out += [f"| {s} | {k.replace('_', ' ')} | {n} |" for (s, k), n in sorted(per.items())]

    # the seeded evaluation
    ev = latest_manifest(store, EVAL)
    out += ["", "## Seeded artefacts", ""]
    if ev and ev["status"] == "passed" and ev["params"].get("as_of") == as_of.isoformat():
        seeds = ev["params"]["seeds"]
        out += [f"`moria eval artefacts` (`{ev['run_id']}`): {ev['counts']['caught']} of {len(seeds)} seeded "
                f"artefacts flagged by their check; {ev['counts']['controls_ok']} of {len(seeds)} controls detected "
                "without it. Details: `reports/eval/artefacts.md`.", ""]  # fmt: skip
    else:
        out.append("No seeded evaluation for this date: run `moria eval artefacts`.")
    out += ["", "## How to read these numbers", "",
            "- A **trend** is significant in at least 2 of 3 windows after Holm's adjustment within its family "
            "(a source's taxonomy level or dataflow, one scope, one frequency); counts are tested as shares of the "
            "source's volume, on a log scale. Benjamini-Hochberg's count is shown only for comparison.",
            "- An **acceleration**, an **anomaly** and a **change in level** must also be material: a change of at "
            "least 0.10 a year in growth, or at least 25% off the expected value (config/detect.yaml).",
            "- A **weak signal** needs at least 3 items (one per de-duplication group) from at least 2 sources.",
            "- A **flag** says the candidate would not stand without the evidence the check doubts; the candidate "
            "stays in the list, marked.", ""]  # fmt: skip
    return "\n".join(out)
