"""`moria evidence-report`: a profile of the evidence layer after `moria prepare`, safe for the public repo
(aggregates only: counts by source, family, date basis, finding code, rule and tag; never titles, text, URLs or
keyphrases, which come from the evidence). Written to `reports/evidence-layer.md`."""

from __future__ import annotations

import duckdb

from .features import DEDUP, EMBED, INDEX, KEYPHRASES
from .iprmetrics import COMMAND as IPRM
from .normalise import COMMAND as NORMALISE
from .store import Store
from .tables import cache_root, fetch_outputs, latest_manifest
from .tags import COMMAND as TAG


def _files(paths) -> str:
    return "[" + ", ".join(f"'{p.as_posix()}'" for p in sorted(paths)) + "]"


def _table(header: list[str], rows: list[tuple]) -> list[str]:
    def cell(v):
        if isinstance(v, float):
            return f"{v:.2f}"
        if isinstance(v, int):
            return f"{v:,}"
        return "" if v is None else str(v)

    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---:" if i else "---" for i in range(len(header))) + "|"]
    out += ["| " + " | ".join(cell(v) for v in r) + " |" for r in rows]
    return out


def evidence_report(store: Store) -> str:
    runs = {c: latest_manifest(store, c) for c in (NORMALISE, EMBED, DEDUP, KEYPHRASES, TAG, INDEX, IPRM)}
    lines = ["# The evidence layer", "",
             "Generated by `moria evidence-report` from the latest run of each stage; aggregates only.", "",
             "| Stage | Run | Status | Commit |", "|---|---|---|---|"]  # fmt: skip
    for c, m in runs.items():
        if m:
            git = m.get("git") or {}
            commit = (git.get("commit") or "")[:7] + (" (dirty)" if git.get("dirty") else "")
            lines.append(f"| `{c}` | `{m['run_id']}` | {m['status']} | `{commit}` |")
        else:
            lines.append(f"| `{c}` | not run | | |")
    con = duckdb.connect()
    n = runs[NORMALISE]
    if not n or n["status"] != "passed":
        return "\n".join(lines)
    out = fetch_outputs(store, n, "lake/", cache_root())
    docs = [p for k, p in out.items() if k.startswith("lake/documents/")]
    series = [p for k, p in out.items() if k.startswith("lake/series/")]
    obs = [p for k, p in out.items() if k.startswith("lake/observations/")]
    quarantine = [p for k, p in out.items() if k.startswith("lake/quarantine/")]
    con.execute(f"CREATE VIEW d AS SELECT * FROM read_parquet({_files(docs)})")
    total = con.execute("SELECT count(*), count(DISTINCT source) FROM d").fetchone()
    lines += ["", f"## Documents: {total[0]:,} items from {total[1]} sources", "",
              "`observable_at` is the source's own date (source), Moria's first sight when the source gives none "
              "(first sight), or first sight when the source's date is later (clamped).", ""]  # fmt: skip
    rows = con.execute(
        "SELECT source, any_value(family), count(*), count(*) FILTER (observable_basis = 'source'), "
        "count(*) FILTER (observable_basis = 'first_sight'), count(*) FILTER (observable_basis = 'clamped'), "
        "min(year(observable_at))::VARCHAR, max(year(observable_at))::VARCHAR, count(*) FILTER (text_stored), "
        "count(*) FILTER (n_versions > 1) FROM d GROUP BY 1 ORDER BY 1"
    ).fetchall()
    lines += _table(["Source", "Family", "Items", "Source date", "First sight", "Clamped", "From", "To",
                     "Text stored", "Revised"], rows)  # fmt: skip
    lines += ["", "**The sweep** (findings by code; high severity is quarantined, the rest kept and marked):", ""]
    rows = con.execute(
        "SELECT c, count(*), count(DISTINCT source) FROM (SELECT unnest(sweep_codes) AS c, source FROM d) "
        "GROUP BY 1 ORDER BY 2 DESC"
    ).fetchall()
    q = con.execute(f"SELECT count(*) FROM read_parquet({_files(quarantine)})").fetchone()[0] if quarantine else 0
    lines += [*_table(["Finding", "Items", "Sources"], rows), "", f"Quarantined: {q:,} items."]
    con.execute(f"CREATE VIEW s AS SELECT * FROM read_parquet({_files(series)})")
    con.execute(f"CREATE VIEW o AS SELECT * FROM read_parquet({_files(obs)})")
    rows = con.execute(
        "SELECT s.source, count(*), sum(n_obs), max(n_vintages), min(first_period), max(last_period) FROM s "
        "GROUP BY 1 ORDER BY 1"
    ).fetchall()
    lines += ["", "## Series and observations", "", "A series' observations are kept per vintage; `n_obs` counts "
              "the latest vintage's periods.", ""]  # fmt: skip
    lines += _table(["Source", "Series", "Observations (latest)", "Most vintages", "First period", "Last period"], rows)
    kinds = con.execute("SELECT period_kind, count(*) FROM o GROUP BY 1 ORDER BY 2 DESC").fetchall()
    lines += ["", "Observations by period kind: " + ", ".join(f"{k} {v:,}" for k, v in kinds) + "."]
    m = runs[IPRM]
    if m and m["status"] == "passed":
        ip = fetch_outputs(store, m, "lake/ipr_metrics/series", cache_root())
        rows = con.execute(
            f"SELECT measure, count(*), string_agg(DISTINCT split_part(series_id, '|', 3), ', ' ORDER BY "
            f"split_part(series_id, '|', 3)) FROM read_parquet({_files(ip.values())}) GROUP BY 1 ORDER BY 1"
        ).fetchall()
        lines += ["", f"## IP RAPID metrics (release {m['params']['release']})", "",
                  *_table(["Metric", "Series", "Rights"], rows), "",
                  "Left out as discontinued or too sparse (no month in the last 12): "
                  + (", ".join(f"`{d}`" for d in m["params"].get("discontinued", [])) or "none") + "."]  # fmt: skip
    e = runs[EMBED]
    if e and e["status"] == "passed":
        lines += ["", "## Embeddings", "", f"Model `{e['params'].get('model')}`; "
                  f"{e['counts'].get('documents', 0):,} documents, {e['counts'].get('embedded', 0):,} embedded in "
                  f"this run (the rest reused or carried over)."]  # fmt: skip
    dd = runs[DEDUP]
    if dd and dd["status"] == "passed":
        g = fetch_outputs(store, dd, "features/dedup/", cache_root())
        con.execute(f"CREATE VIEW g AS SELECT * FROM read_parquet({_files(g.values())})")
        rows = con.execute(
            "SELECT source, count(*), count(DISTINCT dedup_group), count(*) FILTER (rule = 'url'), "
            "count(*) FILTER (rule = 'title'), count(*) FILTER (rule = 'cosine') FROM g GROUP BY 1 "
            "HAVING count(*) > count(DISTINCT dedup_group) ORDER BY 1"
        ).fetchall()
        c = dd["counts"]
        lines += ["", "## De-duplication", "", f"{c.get('items', 0):,} items in {c.get('groups', 0):,} groups; "
                  f"{c.get('groups_with_copies', 0):,} groups have copies. Joins: URL {c.get('joined_url', 0):,}, "
                  f"title {c.get('joined_title', 0):,}, cosine {c.get('joined_cosine', 0):,}. Sources with copies:",
                  "", *_table(["Source", "Items", "Groups", "By URL", "By title", "By cosine"], rows)]  # fmt: skip
    k = runs[KEYPHRASES]
    if k and k["status"] == "passed":
        c = k["counts"]
        lines += ["", "## Keyphrases", "", f"{c.get('vocabulary', 0):,} phrases in the vocabulary; "
                  f"{c.get('keyphrases', 0):,} kept for {c.get('documents_with_keyphrases', 0):,} of "
                  f"{c.get('documents', 0):,} documents. The phrases themselves stay in the bucket."]  # fmt: skip
        vocab = fetch_outputs(store, k, "features/keyphrases/vocabulary", cache_root())
        rows = con.execute(
            f"SELECT n_sources, count(*) FROM (SELECT least(n_sources, 5) AS n_sources FROM "
            f"read_parquet({_files(vocab.values())})) GROUP BY 1 ORDER BY 1"
        ).fetchall()
        lines += ["", "Phrases by the number of sources they appear in (5 means 5 or more): "
                  + ", ".join(f"{a}: {b:,}" for a, b in rows) + "."]  # fmt: skip
    t = runs[TAG]
    if t and t["status"] == "passed":
        tg = fetch_outputs(store, t, "features/tags/", cache_root())
        con.execute(f"CREATE VIEW t AS SELECT * FROM read_parquet({_files(tg.values())})")
        lines += ["", "## Tags (zero-shot, uncalibrated until the owner's labels)", "",
                  f"Tagger `{t['params']['tagger']}`; the owner's territory context "
                  f"{'was' if t['params'].get('territory_context') else 'was not'} used for the territory "
                  "prototypes. Shares of each source's items by top ring and PESTLE origin, and the share matching "
                  "at least one territory or theme term:", ""]  # fmt: skip
        rows = con.execute(
            "SELECT d.source, count(*), avg((ring_top = 'core')::INT), avg((ring_top = 'adjacent')::INT), "
            "avg((ring_top = 'wider_world')::INT), mode(pestle_top), avg((len(term_groups) > 0)::INT) "
            "FROM t JOIN d USING (item_id) GROUP BY 1 ORDER BY 1"
        ).fetchall()
        lines += _table(["Source", "Items", "Core", "Adjacent", "Wider world", "Commonest PESTLE", "Term match"], rows)
        rows = con.execute(
            "SELECT tt, count(*) FROM (SELECT unnest(term_territories) AS tt FROM t) GROUP BY 1 ORDER BY 1"
        ).fetchall()
        lines += ["", "Items matching a territory's terms: " + ", ".join(f"{a} {b:,}" for a, b in rows) + "."]
        rows = con.execute(
            "SELECT known_trend_top, count(*), median(known_trend_sim) FROM t GROUP BY 1 ORDER BY 2 DESC LIMIT 8"
        ).fetchall()
        nearest = ", ".join(f"{a} {b:,} ({c:.2f})" for a, b, c in rows)
        lines += ["", "Nearest known trend (the eight commonest; similarity medians are in a narrow band, so this "
                  f"is a weak tag until calibrated): {nearest}."]  # fmt: skip
        least = con.execute("SELECT count(*) FROM t WHERE ring_margin < 0.2").fetchone()[0]
        lines += ["", f"Items the ring tagger is least sure of (margin under 0.2): {least:,}; the labelling sample "
                  "draws about 50 of its 200 items from these (docs/mining-explained.md)."]  # fmt: skip
    i = runs[INDEX]
    if i and i["status"] == "passed":
        size = next((o["bytes"] for o in i["outputs"] if o["key"].endswith("bm25.duckdb")), 0)
        lines += ["", "## BM25 index", "", f"{i['counts'].get('documents', 0):,} documents, "
                  f"{size / 1e6:,.0f} MB (`features/index/bm25.duckdb`; `moria search`)."]  # fmt: skip
    return "\n".join(lines) + "\n"
